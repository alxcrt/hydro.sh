import { describe, expect, test } from "bun:test";
import { createCookieGetter, getCookies } from "better-auth/cookies";
import { Hono } from "hono";
import {
	authCookieConfig,
	expireLegacyAuthCookies,
	legacyAuthCookieExpirations,
	shouldExpireLegacyAuthCookies,
} from "./auth-cookies";

describe("auth cookie domain", () => {
	test("scopes production cookies to the shared frontend and API subtree", () => {
		const config = authCookieConfig({
			production: true,
			domain: "hydro.alexcretu.com",
			frontendOrigin: "https://hydro.alexcretu.com",
			apiUrl: "https://api.hydro.alexcretu.com",
		});
		expect(config).toMatchObject({
			cookiePrefix: "hydro.sh.v2",
			crossSubDomainCookies: {
				enabled: true,
				domain: ".hydro.alexcretu.com",
			},
			defaultCookieAttributes: { secure: true, partitioned: true },
		});
		expect(
			getCookies({
				baseURL: "https://api.hydro.alexcretu.com",
				advanced: config,
			}).sessionToken,
		).toMatchObject({
			name: "__Secure-hydro.sh.v2.session_token",
			attributes: { domain: ".hydro.alexcretu.com", partitioned: true },
		});
	});

	test("rejects the old broad domain and sibling API hostname", () => {
		expect(() =>
			authCookieConfig({
				production: true,
				domain: "alexcretu.com",
				frontendOrigin: "https://hydro.alexcretu.com",
				apiUrl: "https://hydroapi.alexcretu.com",
			}),
		).toThrow();
		expect(() =>
			authCookieConfig({
				production: true,
				domain: "hydro.alexcretu.com",
				frontendOrigin: "https://hydro.alexcretu.com",
				apiUrl: "https://hydroapi.alexcretu.com",
			}),
		).toThrow();
	});

	test("requires HTTPS for public production origins but permits the loopback image fixture", () => {
		expect(() =>
			authCookieConfig({
				production: true,
				domain: "hydro.alexcretu.com",
				frontendOrigin: "http://hydro.alexcretu.com",
				apiUrl: "https://api.hydro.alexcretu.com",
			}),
		).toThrow();
		expect(
			authCookieConfig({
				production: true,
				domain: "localhost",
				frontendOrigin: "http://127.0.0.1:3000",
				apiUrl: "http://127.0.0.1:3001",
			}).cookiePrefix,
		).toBe("hydro.sh.v2");
		expect(() =>
			authCookieConfig({
				production: true,
				domain: "localhost",
				frontendOrigin: "https://hydro.alexcretu.com",
				apiUrl: "https://api.hydro.alexcretu.com",
			}),
		).toThrow();
	});

	test("does not change development cookie behavior", () => {
		expect(authCookieConfig({ production: false })).toEqual({
			cookiePrefix: "hydro.sh",
		});
	});
});

describe("legacy cookie cleanup", () => {
	test("covers the cookie names generated by the installed Better Auth version", () => {
		const options = {
			baseURL: "https://hydroapi.alexcretu.com",
			advanced: {
				cookiePrefix: "hydro.sh",
				crossSubDomainCookies: {
					enabled: true,
					domain: ".alexcretu.com",
				},
				defaultCookieAttributes: {
					secure: true,
					httpOnly: true,
					sameSite: "none" as const,
					partitioned: true,
				},
			},
		};
		const cookies = getCookies(options);
		const createCookie = createCookieGetter(options);
		const names = [
			...Object.values(cookies).map((cookie) => cookie.name),
			createCookie("oauth_state").name,
			createCookie("state").name,
		];
		for (const name of names) {
			expect(legacyAuthCookieExpirations(`${name}=old`)).toHaveLength(2);
		}
	});

	test("expires only old parent-domain names in both partition modes", () => {
		const headers = legacyAuthCookieExpirations(
			"__Secure-hydro.sh.session_token=old; __Secure-hydro.sh.session_data.0=chunk; __Secure-hydro.sh.v2.session_token=new; other=value",
		);
		expect(headers).toHaveLength(4);
		for (const header of headers) {
			expect(header).toContain("Domain=.alexcretu.com");
			expect(header).toContain("Max-Age=0");
			expect(header).toContain("Path=/");
			expect(header).not.toContain("hydro.sh.v2");
		}
		expect(
			headers.filter((header) => header.includes("Partitioned")),
		).toHaveLength(2);
	});

	test("bounds cleanup headers while prioritizing the session token", () => {
		const chunks = Array.from(
			{ length: 20 },
			(_, index) => `__Secure-hydro.sh.session_data.${index}=part`,
		);
		const headers = legacyAuthCookieExpirations(
			`${chunks.join("; ")}; __Secure-hydro.sh.session_token=old`,
		);
		expect(headers).toHaveLength(32);
		expect(headers[0]).toContain("hydro.sh.session_token=");
	});

	test("preserves new auth Set-Cookie headers on API responses", async () => {
		const app = new Hono();
		app.use("*", expireLegacyAuthCookies);
		app.get("/", (context) => {
			context.header(
				"Set-Cookie",
				"__Secure-hydro.sh.v2.session_token=new; Domain=.hydro.alexcretu.com; Path=/; Secure",
				{ append: true },
			);
			return context.text("OK");
		});
		const response = await app.request("https://api.hydro.alexcretu.com/", {
			headers: { Cookie: "__Secure-hydro.sh.session_token=old" },
		});
		expect(response.headers.getSetCookie()).toHaveLength(3);
		expect(response.headers.getSetCookie()[0]).toContain("hydro.sh.v2");
	});

	test("runs cleanup only on the cutover domain", () => {
		expect(shouldExpireLegacyAuthCookies(true, "hydro.alexcretu.com")).toBe(
			true,
		);
		expect(shouldExpireLegacyAuthCookies(true, "localhost")).toBe(false);
		expect(shouldExpireLegacyAuthCookies(false, "hydro.alexcretu.com")).toBe(
			false,
		);
	});
});
